'use client';

import React, { useEffect, useState } from 'react';
import Link from 'next/link';
import { useParams } from 'next/navigation';
import {
  getAnalysis,
  getExportText,
  getExportDownloadUrl,
  AnalysisDetail,
  ApiError,
} from '../../../../lib/api';
import { ScoreGateHeader } from '../../../../components/ScoreGateHeader';

export default function AnalysisReportPage() {
  const params = useParams();
  const analysisId = params?.id as string;

  const [analysis, setAnalysis] = useState<AnalysisDetail | null>(null);
  const [reportMarkdown, setReportMarkdown] = useState<string>('');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<{ code: string; message: string; details: string[] } | null>(null);

  useEffect(() => {
    if (!analysisId) return;
    setLoading(true);
    setError(null);

    Promise.all([
      getAnalysis(analysisId),
      getExportText(analysisId, 'md'),
    ])
      .then(([anlData, mdText]) => {
        setAnalysis(anlData);
        setReportMarkdown(mdText);
        setLoading(false);
      })
      .catch((err) => {
        if (err instanceof ApiError) {
          setError({ code: err.code, message: err.message, details: err.details });
        } else {
          setError({ code: 'ERROR', message: (err as Error).message, details: [] });
        }
        setLoading(false);
      });
  }, [analysisId]);

  if (loading) {
    return (
      <div className="card" style={{ textAlign: 'center', padding: '4rem 2rem', color: 'var(--text-muted)' }}>
        Loading report for analysis {analysisId}...
      </div>
    );
  }

  if (error || !analysis) {
    return (
      <div>
        <div style={{ marginBottom: '1.5rem' }}>
          <Link href="/" style={{ color: 'var(--text-muted)', fontSize: '0.875rem' }}>
            ← Back to Dashboard
          </Link>
        </div>
        <div className="alert alert-error">
          <div className="alert-title">{error ? `[${error.code}] Report Unavailable` : 'Analysis Not Found'}</div>
          <div>{error ? error.message : `Analysis ${analysisId} could not be loaded.`}</div>
          {error && error.details.length > 0 && (
            <ul className="alert-details-list">
              {error.details.map((d, i) => (
                <li key={i}>{d}</li>
              ))}
            </ul>
          )}
        </div>
      </div>
    );
  }

  return (
    <div>
      <div style={{ marginBottom: '1.5rem' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: '1rem' }}>
          <div>
            <Link href={`/analyses/${analysisId}`} style={{ color: 'var(--text-muted)', fontSize: '0.875rem' }}>
              ← Back to Analysis Results
            </Link>
            <h1 style={{ fontSize: '1.75rem', fontWeight: 700, color: '#ffffff', marginTop: '0.25rem' }}>
              Validation Report: <span className="mono" style={{ color: 'var(--accent-cyan)' }}>{analysis.id}</span>
            </h1>
            <div style={{ color: 'var(--text-muted)', fontSize: '0.8125rem', marginTop: '0.25rem' }}>
              Format: Markdown (as generated by backend export engine)
            </div>
          </div>

          {/* Download Buttons */}
          <div style={{ display: 'flex', gap: '0.75rem', flexWrap: 'wrap' }}>
            <a
              href={getExportDownloadUrl(analysis.id, 'md')}
              download
              className="btn btn-secondary"
              style={{ fontSize: '0.8125rem' }}
            >
              📥 Download MD
            </a>
            <a
              href={getExportDownloadUrl(analysis.id, 'json')}
              download
              className="btn btn-secondary"
              style={{ fontSize: '0.8125rem' }}
            >
              📥 Download JSON
            </a>
            <a
              href={getExportDownloadUrl(analysis.id, 'csv')}
              download
              className="btn btn-secondary"
              style={{ fontSize: '0.8125rem' }}
            >
              📥 Download CSV
            </a>
          </div>
        </div>
      </div>

      {/* Score beside the gate (never re-computed) */}
      <ScoreGateHeader score={analysis.quality_score} gate={analysis.gate} />

      {/* Preformatted report view showing markdown text as-is */}
      <div className="card" style={{ padding: '1rem' }}>
        <div className="card-title" style={{ marginBottom: '0.75rem', fontSize: '0.9375rem' }}>
          <span>📄 Canonical Report Preview</span>
        </div>
        <pre className="report-pre">{reportMarkdown}</pre>
      </div>
    </div>
  );
}
